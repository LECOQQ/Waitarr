"""Every agent name is refused by every rule that refuses an agent."""

import importlib
import sys
from pathlib import Path

import pytest

SCRIPTS = Path(__file__).resolve().parents[2] / "scripts"
sys.path.insert(0, str(SCRIPTS))

check_ai_hygiene = importlib.import_module("check_ai_hygiene")
check_commit_provenance = importlib.import_module("check_commit_provenance")

NAMES = check_commit_provenance.AGENT_NAMES

HYGIENE_RULES = {rule.identifier: rule for rule in check_ai_hygiene.RULES}


def test_the_list_names_codex():
    assert "codex" in NAMES


@pytest.mark.parametrize("name", NAMES)
@pytest.mark.parametrize(
    "template",
    [
        "Co-Authored-By: {name} <noreply@example.com>",
        "{name}-Session: https://example.com/abc",
        "Generated with {name}",
    ],
)
def test_provenance_refuses_every_name(name, template):
    line = template.format(name=name)
    assert check_commit_provenance.offending_lines(f"fix: x\n\n{line}\n")


@pytest.mark.parametrize("name", NAMES)
@pytest.mark.parametrize(
    ("rule", "template"),
    [
        ("agent-co-author", "Co-Authored-By: {name} <noreply@example.com>"),
        ("generation-notice", "generated by {name}"),
        ("generation-notice", "written by {name}"),
    ],
)
def test_hygiene_refuses_every_name(name, rule, template):
    assert HYGIENE_RULES[rule].pattern.search(template.format(name=name))


def test_a_human_co_author_stays_legitimate():
    message = "fix: x\n\nCo-Authored-By: Jane Doe <jane@example.com>\n"
    assert check_commit_provenance.offending_lines(message) == []
    pattern = HYGIENE_RULES["agent-co-author"].pattern
    assert not pattern.search("Co-Authored-By: Jane Doe <jane@example.com>")
